package com.floop.phonebook.service.impl;

import com.floop.phonebook.config.JwtUtil;
import com.floop.phonebook.dto.AuthResponse;
import com.floop.phonebook.dto.LoginRequest;
import com.floop.phonebook.dto.RegisterRequest;
import com.floop.phonebook.entity.UserEntity;
import com.floop.phonebook.exception.BadRequestException;
import com.floop.phonebook.repository.UserRepository;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.security.authentication.AuthenticationManager;
import org.springframework.security.authentication.BadCredentialsException;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.crypto.password.PasswordEncoder;

import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class AuthServiceImplTest {

    @Mock private UserRepository userRepository;
    @Mock private  PasswordEncoder passwordEncoder;
    @Mock private  JwtUtil jwtUtil;
    @Mock private  AuthenticationManager authenticationManager;

    @InjectMocks
    private AuthServiceImpl authService;

    // happy path
    @Test
    void register_whenUsernameIsFree_savesUserWithEncodedPassword(){
       RegisterRequest request = new RegisterRequest();
       request.setUsername("ali");
       request.setPassword("123456");
       request.setEmail("test@gmail.com");
       when(passwordEncoder.encode(request.getPassword())).thenReturn("encoded");

       String result = authService.register(request);

        ArgumentCaptor<UserEntity> captor = ArgumentCaptor.forClass(UserEntity.class);
        verify(userRepository).save(captor.capture());
        UserEntity saved = captor.getValue();

        assertThat(saved.getPassword()).isEqualTo("encoded");
        assertThat(saved.getUsername()).isEqualTo(request.getUsername());
        assertThat(saved.getEmail()).isEqualTo(request.getEmail());
        assertThat(result).contains("is registered");
    }

    @Test
    void login_whenCredentialsAreValid_returnsToken(){
        LoginRequest request = new LoginRequest();
        request.setUsername("ali");
        request.setPassword("123456");
        when(authenticationManager.authenticate(any()))
                .thenReturn(new UsernamePasswordAuthenticationToken(request.getUsername(),null));
        when(jwtUtil.generateToken(request.getUsername())).thenReturn("autogenerated");

        AuthResponse authResponse=authService.login(request);

        assertThat(authResponse.getToken()).isEqualTo("autogenerated");


    }




    // error cases
    @Test
    void register_whenUsernameAlreadyExists_throwsBadRequest(){
        RegisterRequest request = new RegisterRequest();
        request.setUsername("ali");
        UserEntity entity = new UserEntity();
        when(userRepository.findByUsername("ali")).thenReturn(Optional.of(entity));

        assertThatThrownBy(()->authService.register(request))
                .isInstanceOf(BadRequestException.class)
                .hasMessageContaining("already in use");
        verify(userRepository,never()).save(any());
    }

    @Test
    void login_whenInvalidPassword_doesNotCreateToken(){
        LoginRequest request = new LoginRequest();
        request.setUsername("ali");
        request.setPassword("wrong");

        when(authenticationManager.authenticate(any()))
                .thenThrow(new BadCredentialsException("bad"));

        assertThatThrownBy(()->authService.login(request))
                .isInstanceOf(BadCredentialsException.class);
        verifyNoInteractions(jwtUtil);
    }

}